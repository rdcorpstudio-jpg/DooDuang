function pairKey(a: number, b: number) {
  return a < b ? `${a}-${b}` : `${b}-${a}`;
}

export type DailyLuckyNumbers = {
  dayKey: string;
  digits: [number, number, number];
  pair: {
    a: number;
    b: number;
    title: string;
    blurb: string;
  };
};

export function pickDailyLuckyNumbers(
  seedExtra = "",
  day = new Date(),
): DailyLuckyNumbers {
  const dayKey = bangkokDayKey(day);
  const seed = `${dayKey}|lucky|${seedExtra}`;
  const pool = [1, 2, 3, 4, 5, 6, 7, 8, 9];
  const digits: number[] = [];
  for (let i = 0; i < 3; i++) {
    const idx = hashSeed(`${seed}|n${i}`) % pool.length;
    digits.push(pool.splice(idx, 1)[0]!);
  }

  const combos: [number, number][] = [
    [digits[0]!, digits[1]!],
    [digits[1]!, digits[2]!],
    [digits[0]!, digits[2]!],
  ];
  let best = combos[0]!;
  let bestDef = LUCKY_PAIR_DEFS[pairKey(best[0], best[1])];
  for (const combo of combos) {
    const def = LUCKY_PAIR_DEFS[pairKey(combo[0], combo[1])];
    if (def) {
      best = combo;
      bestDef = def;
      break;
    }
  }
  if (!bestDef) {
    bestDef = {
      title: "คู่เลขนำโชคของวันนี้",
      blurb: "ใช้เป็นเครื่องเตือนใจ ให้โฟกัสสิ่งสำคัญและเดินเกมด้วยสติ",
    };
  }

  const [a, b] = best[0] < best[1] ? best : [best[1], best[0]];

  return {
    dayKey,
    digits: [digits[0]!, digits[1]!, digits[2]!],
    pair: {
      a,
      b,
      title: bestDef.title,
      blurb: bestDef.blurb,
    },
  };
}

export function luckyDigitMeaning(n: number) {
  return LUCKY_DIGIT_MEANINGS[n] ?? "";
}
