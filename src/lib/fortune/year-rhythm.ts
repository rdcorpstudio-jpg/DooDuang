export function scoreBand(score: number) {
  if (score >= 10) {
    return {
      label: "พลังสูง",
      meaning: "จังหวะเปิด อยากดันเรื่องไหนให้สุด ช่วงนี้แรงส่งมาเต็ม",
      strength: "คิดออกไว · ตัดสินใจได้ · โอกาสวิ่งเข้าหา",
      use: "เลือกเรื่องใหญ่ไว้หนึ่งถึงสองเรื่อง ทุ่มให้จบ อย่าหว่านจนแรงหมดกลางทาง",
    };
  }
  if (score >= 8) {
    return {
      label: "กำลังดี",
      meaning: "ไปได้เรื่อย ๆ ลื่นดี ถ้าไม่โฟกัสแตกไปหลายทาง",
      strength: "แรงมาต่อเนื่อง · มีเวลาคิดก่อนลงมือ",
      use: "เก็บงานที่ใกล้จบให้เสร็จก่อน แล้วค่อยเปิดเรื่องใหม่",
    };
  }
  if (score >= 6) {
    return {
      label: "ปานกลาง",
      meaning: "ไม่หวือหวา แต่คุมได้ ถ้าไม่หอบเรื่องเยอะเกินตัว",
      strength: "ใจนิ่งพอจะวางแผน · ปรับตามหน้างานได้",
      use: "ตัดเรื่องที่ยังไม่ด่วนออกก่อน เหลือไว้เฉพาะเรื่องที่กระทบผลจริง",
    };
  }
  if (score >= 4) {
    return {
      label: "ชะลอ",
      meaning: "แรงยังไม่เต็ม ช่วงนี้เหมาะจัดของในชีวิตให้เข้าที่มากกว่าเร่ง",
      strength: "เห็นรูรั่วชัด · ตัดของที่ไม่จำเป็นได้ง่าย",
      use: "อย่าเพิ่งขยายอะไรใหญ่ เก็บงาน เก็บบ้าน เก็บใจ ให้เรียบก่อน",
    };
  }
  return {
    label: "ระวัง",
    meaning: "ช่วงนี้หนักหน่อย อย่าเพิ่งตัดสินใจเรื่องใหญ่ตอนที่ใจยังไม่พร้อม",
    strength: "ได้เห็นขอบของตัวเอง · รู้ว่าอะไรสำคัญจริง",
    use: "พักให้พอ เล่าให้คนที่ไว้ใจฟัง แล้วเลื่อนเรื่องใหญ่ออกไปถ้ายังเลื่อนได้",
  };
}

