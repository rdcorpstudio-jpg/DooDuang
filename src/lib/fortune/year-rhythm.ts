export function yearSlotIndex(ce: number, nowCe = new Date().getFullYear()) {
  return ce - (nowCe - 2);
}

export function yearDetailForCe(ce: number, nowCe = new Date().getFullYear()) {
  const i = yearSlotIndex(ce, nowCe);
  const clamped = Math.max(0, Math.min(YEAR_DETAILS.length - 1, i));
  return { i: clamped, detail: YEAR_DETAILS[clamped]! };
}
