export interface FortuneProfile {
  realName: string;
  nickname: string;
  birthDate: string;
  gender: string;
  /** Optional HH:mm */
  birthTime?: string;
  /** Optional focus: life | work | money | love | health */
  focus?: string;
}

export function generateFortune(
  type: ReadingType,
  profile: FortuneProfile,
  date = new Date()
): { title: string; content: string; extras?: Record<string, string> } {
  const seed = `${type}-${profile.realName}-${profile.nickname}-${profile.birthDate}-${profile.gender}-${date.toISOString().slice(0, 10)}`;
  const { nickname } = profile;

  const name = nickname.replace(/^คุณ\s*/, "").trim();
  const address = name ? `คุณ${name}` : "คุณ";
  const personalize = (base: string) => `${address} — ${base}`;
  const titleFor = (label: string) => `${label}ของ${address}`;

  switch (type) {
    case "daily": {
      const pool = Object.values(DAILY_FORTUNES).flat();
      const index = hashString(seed) % pool.length;
      return {
        title: titleFor("ดวงวันนี้"),
        content: personalize(pool[index]),
        extras: {
          สีมงคล: ["ม่วง", "ทอง", "ขาว", "น้ำเงิน"][hashString(seed) % 4],
          เลขมงคล: String((hashString(seed + "num") % 9) + 1),
          คะแนนดวง: String(60 + (hashString(seed + "score") % 41)) + "/100",
        },
      };
    }
    case "love":
      return {
        title: titleFor("ดวงความรัก"),
        content: personalize(Object.values(LOVE_FORTUNES)[hashString(seed) % 12]),
        extras: {
          โอกาสพบรัก: ["สูงมาก", "ปานกลาง", "ค่อนข้างสูง"][hashString(seed + "love") % 3],
          คำแนะนำ: "เปิดใจรับความรักที่เข้ามา อย่ากลัวที่จะแสดงความรู้สึก",
        },
      };
    case "career":
      return {
        title: titleFor("ดวงการงาน"),
        content: personalize(Object.values(CAREER_FORTUNES)[hashString(seed) % 12]),
        extras: {
          โอกาสก้าวหน้า: ["ไปได้ดี", "ดี", "ปานกลาง"][hashString(seed + "career") % 3],
          คำแนะนำ: "มุ่งมั่นกับเป้าหมาย โอกาสดีกำลังมา",
        },
      };
    case "money":
      return {
        title: titleFor("ดวงการเงิน"),
        content: personalize(Object.values(MONEY_FORTUNES)[hashString(seed) % 12]),
        extras: {
          โชคลาภ: ["ดี", "ปานกลาง", "ต้องคุม"][hashString(seed + "money") % 3],
          คำแนะนำ: "วางแผนการเงิน อย่าใจร้อน",
        },
      };
    case "health":
      return {
        title: titleFor("ดวงสุขภาพ"),
        content: personalize(Object.values(HEALTH_FORTUNES)[hashString(seed) % 12]),
        extras: {
          พลังงาน: ["สูง", "ปานกลาง", "ฟื้นตัว"][hashString(seed + "health") % 3],
          คำแนะนำ: "ดูแลตัวเองทั้งกายและใจ",
        },
      };
    case "overall":
      return {
        title: titleFor("ภาพรวมชีวิต"),
        content: personalize(Object.values(OVERALL_FORTUNES)[hashString(seed) % 12]),
        extras: {
          ดวงโดยรวม: ["ไปได้ดี", "ดี", "ปานกลาง"][hashString(seed + "overall") % 3],
          คำแนะนำ: "เชื่อมั่นในตัวเอง ทุกอย่างจะดีขึ้น",
        },
      };
    case "tarot": {
      const cards = drawTarotSpread(seed, 3);
      const positions = ["อดีต", "ปัจจุบัน", "อนาคต"];
      const content = cards
        .map((card, i) => {
          const orient =
            hashString(`${seed}-orient-${i}`) % 2 === 0
              ? card.upright
              : card.reversed;
          return `${positions[i]} — ${card.nameTh} (${card.nameEn}): ${orient}`;
        })
        .join("\n\n");
      return {
        title: titleFor("ไพ่ทาโรต์ 3 ใบ"),
        content: personalize(content),
        extras: {
          ไพ่ใบที่1: `${cards[0].nameTh} (${positions[0]})`,
          ไพ่ใบที่2: `${cards[1].nameTh} (${positions[1]})`,
          ไพ่ใบที่3: `${cards[2].nameTh} (${positions[2]})`,
        },
      };
    }
    default:
      return { title: "ดวง", content: "ไม่พบข้อมูล" };
  }
}
