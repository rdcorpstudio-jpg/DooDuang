/** Month-card copy bank — richer than scoreBand.meaning, picked by seed+month */

export type MonthDetail = {
  overview: string;
  /** Main focus this month (work / money / love / health) */
  focus: string;
  do: string;
  watch: string;
  opportunity: string;
  /** Early / mid / late month nuance */
  timing: string;
  closing: string;
};

export type MonthBandKey = "high" | "good" | "mid" | "slow" | "caution";

export function monthBandKey(score: number): MonthBandKey {
  if (score >= 10) return "high";
  if (score >= 8) return "good";
  if (score >= 6) return "mid";
  if (score >= 4) return "slow";
  return "caution";
}

function hashSeed(input: string) {
  let h = 2166136261;
  for (let i = 0; i < input.length; i++) {
    h ^= input.charCodeAt(i);
    h = Math.imul(h, 16777619);
  }
  return Math.abs(h) >>> 0;
}

/** Pick a variant for this person+month so nearby scores don't feel identical */
export function pickMonthDetail(
  score: number,
  seed: string,
  monthIndex?: number,
  yearCe?: number
): MonthDetail {
  const key = monthBandKey(score);
  const bank = MONTH_DETAILS[key];
  const salt =
    monthIndex !== undefined && yearCe !== undefined
      ? `${seed}|${yearCe}-${monthIndex}|${key}`
      : `${seed}|${key}|${score}`;
  return bank[hashSeed(salt) % bank.length]!;
}

