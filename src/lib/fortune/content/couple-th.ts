export function elementPairKey(a: string, b: string): string {
  const order = ["ไฟ", "ดิน", "ลม", "น้ำ"] as const;
  const ia = order.indexOf(a as (typeof order)[number]);
  const ib = order.indexOf(b as (typeof order)[number]);
  if (ia < 0 || ib < 0) return "ดิน+ลม";
  return ia <= ib ? `${a}+${b}` : `${b}+${a}`;
}
