function hashSeed(input: string) {
  let h = 2166136261;
  for (let i = 0; i < input.length; i++) {
    h ^= input.charCodeAt(i);
    h = Math.imul(h, 16777619);
  }
  return Math.abs(h) >>> 0;
}

export function seamseeTopic(id: SeamseeTopicId) {
  return SEAMSEE_TOPICS.find((t) => t.id === id) ?? SEAMSEE_TOPICS[0];
}

export function seamseeStick(no: number) {
  return STICKS.find((s) => s.no === no) ?? null;
}

export function drawSeamseeStick(seed: string) {
  return STICKS[hashSeed(seed) % STICKS.length]!;
}

export function seamseeReading(stick: Stick, topic: SeamseeTopicId) {
  return {
    title: seamseeTopic(topic).title,
    paragraphs: [`${TOPIC_OPEN[topic]} ${stick.scene}`, stick.advice[topic]] as [
      string,
      string,
    ],
  };
}

export type SeamseeDraw = {
  dayKey: string;
  topic: SeamseeTopicId;
  stickNo: number;
};

export function readTodaySeamsee(now = new Date()): SeamseeDraw | null {
  if (typeof window === "undefined") return null;
  try {
    const raw = localStorage.getItem(STORAGE_KEY);
    if (!raw) return null;
    const parsed = JSON.parse(raw) as SeamseeDraw;
    if (parsed.dayKey !== bangkokDayKey(now)) return null;
    if (!seamseeStick(parsed.stickNo)) return null;
    if (!SEAMSEE_TOPICS.some((t) => t.id === parsed.topic)) return null;
    return parsed;
  } catch {
    return null;
  }
}

export function saveTodaySeamsee(draw: SeamseeDraw) {
  try {
    localStorage.setItem(STORAGE_KEY, JSON.stringify(draw));
  } catch {
    /* ignore quota */
  }
}

export function todaySeamseeKey(now = new Date()) {
  return bangkokDayKey(now);
}
