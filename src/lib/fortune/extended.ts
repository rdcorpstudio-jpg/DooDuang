function normalizeSections(
  sections: FortuneSection[],
  tabIndex: number,
  type: ReadingType,
  nickname: string,
  seed: string
): FortuneSection[] {
  const result = sections.slice(0, 3).map((s) => ({
    ...s,
    content: trimText(s.content, MAX_SECTION_CHARS),
  }));

  const extra = TAB_THIRD_SECTION[type]?.[tabIndex];
  if (result.length < 3 && extra) {
    result.push({
      heading: extra.heading,
      content: trimText(pick(extra.pool(nickname), seed, `t3-${tabIndex}`), MAX_SECTION_CHARS),
    });
  }

  while (result.length < 3) {
    result.push({
      heading: "จุดที่ควรจำ",
      content: trimText(`${nickname} ฟังสัญชาตญาณและใช้เวลาตัดสินใจอย่างมีสติ`, MAX_SECTION_CHARS),
    });
  }

  return result.slice(0, 3);
}

function getSunSign(birthDate: string): string {
  const [, m, d] = birthDate.split("-").map(Number);
  const day = d;
  const month = m;
  if ((month === 3 && day >= 21) || (month === 4 && day <= 19)) return "เมษ";
  if ((month === 4 && day >= 20) || (month === 5 && day <= 20)) return "พฤษภ";
  if ((month === 5 && day >= 21) || (month === 6 && day <= 20)) return "เมถุน";
  if ((month === 6 && day >= 21) || (month === 7 && day <= 22)) return "กรกฎ";
  if ((month === 7 && day >= 23) || (month === 8 && day <= 22)) return "สิงห์";
  if ((month === 8 && day >= 23) || (month === 9 && day <= 22)) return "กันย์";
  if ((month === 9 && day >= 23) || (month === 10 && day <= 22)) return "ตุลย์";
  if ((month === 10 && day >= 23) || (month === 11 && day <= 21)) return "พิจิก";
  if ((month === 11 && day >= 22) || (month === 12 && day <= 21)) return "ธนู";
  if ((month === 12 && day >= 22) || (month === 1 && day <= 19)) return "มังกร";
  if ((month === 1 && day >= 20) || (month === 2 && day <= 18)) return "กุมภ์";
  return "มีน";
}

function getMoonSign(birthDate: string, seed: string): string {
  const signs = [
    "เมษ", "พฤษภ", "เมถุน", "กรกฎ", "สิงห์", "กันย์",
    "ตุลย์", "พิจิก", "ธนู", "มังกร", "กุมภ์", "มีน",
  ];
  return pick(signs, seed, `moon-${birthDate}`);
}

