export function generateExtendedFortune(
  type: ReadingType,
  profile: FortuneProfile
): ExtendedFortuneResult {
  const base = generateFortune(type, profile);
  const seed = `${type}-${profile.realName}-${profile.nickname}-${profile.birthDate}-${profile.gender}`;
  const blueprint = BLUEPRINTS[type] ?? BLUEPRINTS.overall;
  const sun = getSunSign(profile.birthDate);
  const moon = getMoonSign(profile.birthDate, seed);
  const summaries = blueprint.buildSummaries(profile.nickname, seed);

  const tabs: FortuneTab[] = blueprint.labels.map((label, i) => ({
    id: `section-${i}`,
    label,
    heroTitle: blueprint.heroes[i],
    sections: normalizeSections(
      blueprint.buildSections(profile, seed, i, sun, moon),
      i,
      type,
      profile.nickname,
      seed
    ),
    summary: trimText(summaries[i], MAX_SUMMARY_CHARS),
  }));

  return {
    title: base.title,
    preview: base.content,
    tabs,
    highlights: buildHighlights(type, seed, base.extras),
    premium: blueprint.buildPremium(profile, seed, sun),
  };
}

export function getUnlockStorageKey(type: string, profile: FortuneProfile): string {
  return `lukkana-unlock-${type}-${profile.birthDate}-${profile.nickname}`;
}
